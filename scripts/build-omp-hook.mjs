import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const entry = join(root, 'resources', 'omp-patty-hook.ts')
const outFile = join(root, 'resources', 'omp-patty-hook.bundle.js')
const liteModule = join(root, 'integrations', 'omp', 'progressive-highlight-lite.ts')
const scratch = join(root, 'output', 'omp-standard')
const checkMode = process.argv.includes('--check')
const bundleName = 'omp-patty-hook.bundle.js'
const banner = '// Generated by scripts/build-omp-hook.mjs from resources/omp-patty-hook.ts.\n// Do not edit by hand.\n'

function locateBun() {
  const candidates = []
  if (process.env.BUN_EXE) candidates.push(process.env.BUN_EXE)
  candidates.push(join(root, 'output', 'omp-navigation', 'runtime', 'bun-windows-x64', 'bun.exe'))
  candidates.push('bun.exe', 'bun')
  for (const candidate of candidates) {
    try {
      execFileSync(candidate, ['--version'], { stdio: 'ignore' })
      return candidate
    } catch {
      continue
    }
  }
  throw new Error('bun executable not found. Set BUN_EXE or add bun to PATH.')
}

function assertBundleClean(content) {
  const problems = []
  if (/(?:^|\n)\s*(?:import|export)[^\n]*?\bfrom\s*['"]\.[^'"]*['"]/.test(content)) problems.push('relative import')
  if (/\bimport\s*\(\s*['"]\.[^'"]*['"]\s*\)/.test(content)) problems.push('relative dynamic import')
  if (content.includes('new Worker(')) problems.push('new Worker(')
  if (problems.length) throw new Error(`bundle must not contain ${problems.join(', ')}`)
}

const bun = locateBun()
mkdirSync(scratch, { recursive: true })
const outdir = checkMode ? join(scratch, 'check') : join(root, 'resources')
mkdirSync(outdir, { recursive: true })

const runner = join(scratch, 'build-runner.mjs')
const runnerSource = `const result = await Bun.build({
  entrypoints: [${JSON.stringify(entry)}],
  outdir: ${JSON.stringify(outdir)},
  naming: ${JSON.stringify(bundleName)},
  target: 'bun',
  format: 'esm',
  external: ['@oh-my-pi/*'],
  banner: ${JSON.stringify(banner)},
  plugins: [{
    name: 'progressive-highlight-lite',
    setup(build) {
      build.onResolve({ filter: /^\\.\\/progressive-highlight$/ }, () => ({ path: ${JSON.stringify(liteModule)} }))
    }
  }]
})
if (!result.success) {
  for (const log of result.logs) console.error(log)
  process.exit(1)
}
`
writeFileSync(runner, runnerSource)
execFileSync(bun, ['run', runner], { stdio: 'inherit' })

const builtFile = join(outdir, bundleName)
if (!existsSync(builtFile)) throw new Error(`build produced no bundle at ${builtFile}`)
const content = readFileSync(builtFile, 'utf8')
assertBundleClean(content)

if (checkMode) {
  const committed = existsSync(outFile) ? readFileSync(outFile, 'utf8') : ''
  if (committed !== content) {
    console.error('resources/omp-patty-hook.bundle.js is out of date. Run: node scripts/build-omp-hook.mjs')
    process.exit(1)
  }
  console.log('omp hook bundle is up to date')
} else {
  console.log(`wrote resources/omp-patty-hook.bundle.js (${content.length} bytes)`)
}
